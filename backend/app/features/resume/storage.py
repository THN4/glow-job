import asyncio
import json
import logging
import tempfile
import time
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Awaitable, Callable, Generic, TypeVar

from src.resume.schemas.cv_extraction import CvExtractionResult

log = logging.getLogger("cv_extraction")

HOUR = 3600
UPLOAD_TTL = HOUR
JOB_TTL = HOUR
CACHE_TTL = 24 * HOUR

V = TypeVar("V")


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


class TtlDict(Generic[V]):
    """Dict whose entries disappear after a TTL (checked on read)."""

    def __init__(self, ttl_seconds: float, clock: Callable[[], float] = time.monotonic):
        self._ttl = ttl_seconds
        self._clock = clock
        self._data: dict[str, tuple[V, float]] = {}

    def get(self, key: str) -> V | None:
        entry = self._data.get(key)
        if entry is None:
            return None
        if entry[1] <= self._clock():
            self._data.pop(key, None)
            return None
        return entry[0]

    def set(self, key: str, value: V, keep_expiry: bool = False) -> None:
        prev = self._data.get(key)
        expires = prev[1] if keep_expiry and prev else self._clock() + self._ttl
        self._data[key] = (value, expires)

    def delete(self, key: str) -> None:
        self._data.pop(key, None)


@dataclass
class UploadMeta:
    upload_id: str
    file_name: str
    content_type: str
    size: int
    created_at: str
    has_file: bool = False


class LocalUploadStore:
    def __init__(self, directory: Path, public_base_url: str, api_prefix: str):
        self.dir = directory
        self._base = f"{public_base_url.rstrip('/')}{api_prefix}"
        self._metas: TtlDict[UploadMeta] = TtlDict(UPLOAD_TTL)

    def init(self) -> None:
        """Create the temp folder and remove files left over from a previous run."""
        self.dir.mkdir(parents=True, exist_ok=True)
        for f in self.dir.iterdir():
            if f.is_file():
                f.unlink(missing_ok=True)

    def create(self, file_name: str, content_type: str, size: int) -> tuple[UploadMeta, dict[str, Any]]:
        meta = UploadMeta(f"upl_{uuid.uuid4()}", file_name, content_type, size, now_iso())
        self._metas.set(meta.upload_id, meta)
        target = {
            "method": "PUT",
            "url": f"{self._base}/cv/uploads/{meta.upload_id}/file",
            "headers": {"Content-Type": content_type},
        }
        return meta, target

    def get_meta(self, upload_id: str) -> UploadMeta | None:
        return self._metas.get(upload_id)

    def has_file(self, upload_id: str) -> bool:
        m = self._metas.get(upload_id)
        return bool(m and m.has_file)

    def write(self, upload_id: str, data: bytes) -> None:
        meta = self._metas.get(upload_id)
        if meta is None:
            raise KeyError(upload_id)
        self.dir.mkdir(parents=True, exist_ok=True)
        self._path(upload_id).write_bytes(data)
        meta.has_file = True

    def read(self, upload_id: str) -> bytes | None:
        if not self.has_file(upload_id):
            return None
        try:
            return self._path(upload_id).read_bytes()
        except OSError:
            return None

    def delete(self, upload_id: str) -> None:
        self._metas.delete(upload_id)
        self._path(upload_id).unlink(missing_ok=True)

    def _path(self, upload_id: str) -> Path:
        # upload_id is generated by us (upl_<uuid>); strip anything else defensively.
        return self.dir / "".join(c for c in upload_id if c.isalnum() or c in "_-")


@dataclass
class Job:
    job_id: str
    upload_id: str
    session_id: str | None = None
    status: str = "queued"  # queued | processing | succeeded | failed
    stage: str = "reading"  # reading | skills | education | experience | building
    result: CvExtractionResult | None = None
    error: dict[str, Any] | None = None
    created_at: str = field(default_factory=now_iso)
    updated_at: str = field(default_factory=now_iso)


class JobsRepo:
    def __init__(self) -> None:
        self._jobs: TtlDict[Job] = TtlDict(JOB_TTL)

    def create(self, job: Job) -> None:
        self._jobs.set(job.job_id, job)

    def get(self, job_id: str, session_id: str | None = None) -> Job | None:
        job = self._jobs.get(job_id)
        if job is not None and session_id is not None and job.session_id != session_id:
            return None
        return job

    def update(self, job_id: str, **patch: Any) -> None:
        job = self._jobs.get(job_id)
        if job is None:
            return
        for k, v in patch.items():
            setattr(job, k, v)
        job.updated_at = now_iso()

class CacheRepo:
    def __init__(self) -> None:
        self._cache: TtlDict[CvExtractionResult] = TtlDict(CACHE_TTL)

    def get(self, file_hash: str) -> CvExtractionResult | None:
        r = self._cache.get(file_hash)
        return r.model_copy(deep=True) if r else None

    def put(self, file_hash: str, result: CvExtractionResult) -> None:
        self._cache.set(file_hash, result.model_copy(deep=True))


class UsageCounter:
    def __init__(self) -> None:
        self._day = ""
        self._count = 0

    def _roll(self) -> None:
        today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        if today != self._day:
            self._day, self._count = today, 0

    def get_today(self) -> int:
        self._roll()
        return self._count

    def increment_today(self) -> int:
        self._roll()
        self._count += 1
        return self._count


@dataclass
class StoredProfile:
    profile_id: str
    session_id: str
    profile: dict[str, Any]  # CvProfile as camelCase JSON
    created_at: str
    updated_at: str


class FileProfilesRepo:
    """Profiles are kept in a JSON file so they survive restarts during development."""

    def __init__(self, file: Path):
        self._file = file
        self._cache: dict[str, dict[str, Any]] | None = None
        self._lock = asyncio.Lock()

    def _load(self) -> dict[str, dict[str, Any]]:
        if self._cache is None:
            try:
                self._cache = json.loads(self._file.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                self._cache = {}
        return self._cache

    async def get(self, profile_id: str) -> StoredProfile | None:
        raw = self._load().get(profile_id)
        return StoredProfile(**raw) if raw else None

    async def put(self, p: StoredProfile) -> None:
        async with self._lock:
            data = self._load()
            data[p.profile_id] = p.__dict__
            self._file.parent.mkdir(parents=True, exist_ok=True)
            self._file.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")


class JobQueue:
    """In-process FIFO queue, concurrency 1: the local GPU handles one extraction at a time.

    The worker task starts lazily on the first enqueue, so mounting the router into another
    FastAPI app needs no lifespan wiring.
    """

    def __init__(self, handler: Callable[[str], Awaitable[None]]):
        self._handler = handler
        self._queue: asyncio.Queue[str] | None = None
        self._worker: asyncio.Task | None = None

    async def enqueue(self, job_id: str) -> None:
        if self._queue is None:
            self._queue = asyncio.Queue()
        self._queue.put_nowait(job_id)
        if self._worker is None or self._worker.done():
            self._worker = asyncio.get_running_loop().create_task(self._run())

    async def join(self) -> None:
        """Resolves when everything queued so far is processed (used by tests)."""
        if self._queue is not None:
            await self._queue.join()

    async def _run(self) -> None:
        assert self._queue is not None
        while True:
            job_id = await self._queue.get()
            try:
                await self._handler(job_id)
            except Exception:  # the handler records failures itself; this is a last resort
                log.exception("job handler crashed: %s", job_id)
            finally:
                self._queue.task_done()


