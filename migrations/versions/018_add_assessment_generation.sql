-- On-demand question generation for step checks (docs/assessments/question-bank.md).
-- provisional items were drafted by a model while a learner waited. Step checks may use them
-- until a reviewer approves or rejects them. Level checks use approved items only.

ALTER TABLE app.assessment_items DROP CONSTRAINT IF EXISTS assessment_items_status_check;
ALTER TABLE app.assessment_items ADD CONSTRAINT ck_assessment_items_status
    CHECK (status IN ('draft', 'provisional', 'approved', 'rejected', 'retired'));

DROP INDEX IF EXISTS app.ix_assessment_items_chunk;
CREATE INDEX ix_assessment_items_chunk ON app.assessment_items (chunk_id)
    WHERE status IN ('approved', 'provisional');

-- One row per model run for one chunk. Used for the daily cap and to avoid retrying a chunk
-- that produced nothing (outcome empty) or just failed (outcome failed).
CREATE TABLE app.assessment_generations (
    generation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chunk_id bigint NOT NULL,
    skill_id bigint NOT NULL REFERENCES core.skills (skill_id) ON DELETE CASCADE,
    trigger text NOT NULL CHECK (trigger IN ('step_check', 'level_check')),
    model text NOT NULL,
    outcome text NOT NULL DEFAULT 'running' CHECK (outcome IN ('running', 'created', 'empty', 'failed')),
    items_created smallint NOT NULL DEFAULT 0,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz
);
CREATE INDEX ix_assessment_generations_chunk ON app.assessment_generations (chunk_id, started_at DESC);
CREATE INDEX ix_assessment_generations_started ON app.assessment_generations (started_at);
