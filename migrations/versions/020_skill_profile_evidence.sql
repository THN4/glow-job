-- User-managed evidence attached to a canonical skill in the saved profile.
-- Small image data URLs are supported for certificates and self reports (500 KB UI limit).
CREATE TABLE app.user_skill_artifacts (
    artifact_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    skill_id bigint NOT NULL REFERENCES core.skills (skill_id) ON DELETE RESTRICT,
    evidence_type text NOT NULL CHECK (evidence_type IN ('github_project', 'certificate', 'self_report')),
    title varchar(160) NOT NULL CHECK (length(btrim(title)) > 0),
    source_url text,
    notes text NOT NULL DEFAULT '',
    photo_data text CHECK (
        photo_data IS NULL OR (
            length(photo_data) <= 700000
            AND photo_data ~ '^data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/=]+$'
        )
    ),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_skill_artifacts_http_url
        CHECK (source_url IS NULL OR source_url ~* '^https?://'),
    CONSTRAINT ck_user_skill_artifacts_required_content CHECK (
        (evidence_type = 'github_project' AND source_url IS NOT NULL)
        OR (evidence_type = 'certificate' AND (source_url IS NOT NULL OR photo_data IS NOT NULL))
        OR (evidence_type = 'self_report' AND length(btrim(notes)) > 0)
    )
);

CREATE INDEX ix_user_skill_artifacts_user_skill_created
    ON app.user_skill_artifacts (user_id, skill_id, created_at DESC, artifact_id DESC);
