-- Persist the full personal-application tracker state used by the Applications UI.
-- Existing rows keep their current status and notes. This migration does not synthesize history.

ALTER TYPE app.application_status ADD VALUE IF NOT EXISTS 'screening';

ALTER TABLE app.job_applications
    ADD COLUMN company_name text,
    ADD COLUMN job_url text,
    ADD COLUMN job_description text,
    ADD COLUMN location text,
    ADD COLUMN rejection_category text
        CHECK (rejection_category IS NULL OR rejection_category IN (
            'not-specified', 'skill-gap', 'experience', 'interview', 'position-filled', 'other'
        )),
    ADD COLUMN rejection_reason text;

CREATE TABLE app.application_status_events (
    status_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id bigint NOT NULL
        REFERENCES app.job_applications (application_id) ON DELETE CASCADE,
    previous_status app.application_status,
    status app.application_status NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_application_status_events_application_time
    ON app.application_status_events (application_id, occurred_at, status_event_id);
