-- Keep each prior confirmed profile so an accidental overwrite can be undone.
CREATE TABLE app.user_profile_versions (
    version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    profile_id text NOT NULL,
    profile_data jsonb NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    saved_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_user_profile_versions_user_saved
    ON app.user_profile_versions (user_id, saved_at DESC);
