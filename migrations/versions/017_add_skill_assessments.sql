-- Skill assessments: a reviewed question bank, self-check statements, each check a learner
-- takes, and the answers. Step checks verify roadmap study tasks. Level checks and quick
-- questions set a skill level once the learner keeps the result.
-- The migration runner splits statements on semicolons, so comments must not contain one.

-- Levels can now come from a quiz ("assessed") or from the learner's own rating ("self_reported").
ALTER TABLE app.user_skills DROP CONSTRAINT IF EXISTS user_skills_proficiency_basis_check;
ALTER TABLE app.user_skills
    ADD CONSTRAINT ck_user_skills_proficiency_basis CHECK (
        proficiency_basis IN ('explicit', 'inferred', 'unknown', 'self_reported', 'assessed')
    );

-- Single-answer questions. chunk_id is the knowledge chunk whose text supports the answer.
CREATE TABLE app.assessment_items (
    item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id bigint NOT NULL REFERENCES core.skills (skill_id) ON DELETE RESTRICT,
    chunk_id bigint NOT NULL,
    level text NOT NULL CHECK (level IN ('beginner', 'intermediate', 'advanced')),
    stem text NOT NULL,
    options jsonb NOT NULL CHECK (jsonb_typeof(options) = 'array' AND jsonb_array_length(options) = 4),
    answer_index smallint NOT NULL CHECK (answer_index BETWEEN 0 AND 3),
    quote text NOT NULL,
    source_title text NOT NULL,
    source_heading text,
    source_url text,
    content_hash text,
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved', 'rejected', 'retired')),
    generated_by text NOT NULL,
    review_note text,
    created_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz,
    CONSTRAINT uq_assessment_items_stem UNIQUE (skill_id, stem)
);
CREATE INDEX ix_assessment_items_chunk ON app.assessment_items (chunk_id) WHERE status = 'approved';
CREATE INDEX ix_assessment_items_skill_level ON app.assessment_items (skill_id, level) WHERE status = 'approved';

-- "I can..." statements. skill_id NULL rows are generic and use a {skill} placeholder.
CREATE TABLE app.assessment_self_check_statements (
    statement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id bigint REFERENCES core.skills (skill_id) ON DELETE CASCADE,
    level text NOT NULL CHECK (level IN ('beginner', 'intermediate', 'advanced')),
    position smallint NOT NULL CHECK (position BETWEEN 1 AND 9),
    text text NOT NULL
);
CREATE UNIQUE INDEX uq_self_check_statements_skill
    ON app.assessment_self_check_statements (skill_id, level, position) WHERE skill_id IS NOT NULL;
CREATE UNIQUE INDEX uq_self_check_statements_generic
    ON app.assessment_self_check_statements (level, position) WHERE skill_id IS NULL;

-- One row per check. state holds the in-progress level-check queue. summary holds the result.
CREATE TABLE app.skill_assessments (
    assessment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    skill_id bigint REFERENCES core.skills (skill_id) ON DELETE RESTRICT,
    kind text NOT NULL CHECK (kind IN ('step_check', 'level_check', 'quick_question')),
    status text NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'completed', 'abandoned')),
    decision text NOT NULL DEFAULT 'pending' CHECK (decision IN ('pending', 'accepted', 'declined')),
    entry_point text,
    roadmap_id bigint REFERENCES app.roadmaps (roadmap_id) ON DELETE SET NULL,
    step_key text,
    method text CHECK (method IS NULL OR method IN ('quiz', 'self_check')),
    self_check_level text CHECK (self_check_level IS NULL OR self_check_level IN ('beginner', 'intermediate', 'advanced')),
    result_level text CHECK (result_level IS NULL OR result_level IN ('beginner', 'intermediate', 'advanced')),
    confidence text CHECK (confidence IS NULL OR confidence IN ('high', 'medium', 'low')),
    scoring_version text NOT NULL,
    state jsonb NOT NULL DEFAULT '{}'::jsonb,
    summary jsonb NOT NULL DEFAULT '{}'::jsonb,
    started_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz,
    decided_at timestamptz,
    CONSTRAINT ck_skill_assessments_step CHECK (kind <> 'step_check' OR step_key IS NOT NULL)
);
CREATE INDEX ix_skill_assessments_user_started ON app.skill_assessments (user_id, started_at DESC);
CREATE INDEX ix_skill_assessments_user_skill ON app.skill_assessments (user_id, skill_id, decided_at DESC)
    WHERE decision = 'accepted';

CREATE TABLE app.skill_assessment_answers (
    assessment_id bigint NOT NULL REFERENCES app.skill_assessments (assessment_id) ON DELETE CASCADE,
    item_id bigint NOT NULL REFERENCES app.assessment_items (item_id) ON DELETE RESTRICT,
    task_id text,
    level text,
    choice smallint NOT NULL CHECK (choice BETWEEN 0 AND 3),
    correct boolean NOT NULL,
    answered_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (assessment_id, item_id)
);

-- Roadmap tasks ticked by a step check keep a link to it. needs_review marks a task the check failed.
ALTER TABLE app.user_task_progress
    ADD COLUMN verified_by_assessment_id bigint
        REFERENCES app.skill_assessments (assessment_id) ON DELETE SET NULL,
    ADD COLUMN needs_review boolean NOT NULL DEFAULT false;
