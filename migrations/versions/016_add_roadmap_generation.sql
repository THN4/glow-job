-- AI roadmap generation: keep what each roadmap version was built from, the plan
-- structure the UI needs, and per-run token usage for the monthly cost guard.
-- Earlier rows stay valid: every new column is nullable or has a default.

ALTER TABLE app.roadmap_steps
    ADD COLUMN step_key text,
    ADD COLUMN step_kind text
        CHECK (step_kind IS NULL OR step_kind IN ('skill', 'foundation_check', 'project', 'career_activity')),
    ADD COLUMN estimated_hours_min numeric(6, 2)
        CHECK (estimated_hours_min IS NULL OR estimated_hours_min >= 0),
    ADD COLUMN estimated_hours_max numeric(6, 2)
        CHECK (estimated_hours_max IS NULL OR estimated_hours_max >= 0),
    ADD COLUMN why jsonb CHECK (why IS NULL OR jsonb_typeof(why) = 'array'),
    ADD COLUMN depends_on jsonb CHECK (depends_on IS NULL OR jsonb_typeof(depends_on) = 'array'),
    ADD COLUMN citations jsonb CHECK (citations IS NULL OR jsonb_typeof(citations) = 'array'),
    ADD CONSTRAINT ck_roadmap_steps_hour_range CHECK (
        estimated_hours_min IS NULL OR estimated_hours_max IS NULL
        OR estimated_hours_min <= estimated_hours_max
    );
CREATE UNIQUE INDEX uq_roadmap_steps_key
    ON app.roadmap_steps (roadmap_id, step_key) WHERE step_key IS NOT NULL;

ALTER TABLE app.roadmap_tasks
    ADD COLUMN task_kind text CHECK (task_kind IS NULL OR task_kind IN ('learn', 'practice', 'check')),
    ADD COLUMN citations jsonb CHECK (citations IS NULL OR jsonb_typeof(citations) = 'array');

-- Token usage per model call. estimated_cost_usd uses the configured price per token.
-- The migration runner splits statements on semicolons, so comments must not contain one.
ALTER TABLE system.ai_runs
    ADD COLUMN input_tokens integer CHECK (input_tokens IS NULL OR input_tokens >= 0),
    ADD COLUMN output_tokens integer CHECK (output_tokens IS NULL OR output_tokens >= 0),
    ADD COLUMN cache_read_input_tokens integer
        CHECK (cache_read_input_tokens IS NULL OR cache_read_input_tokens >= 0),
    ADD COLUMN cache_creation_input_tokens integer
        CHECK (cache_creation_input_tokens IS NULL OR cache_creation_input_tokens >= 0),
    ADD COLUMN estimated_cost_usd numeric(10, 6)
        CHECK (estimated_cost_usd IS NULL OR estimated_cost_usd >= 0),
    ADD COLUMN metadata jsonb NOT NULL DEFAULT '{}'::jsonb;
CREATE INDEX ix_ai_runs_operation_started_at
    ON system.ai_runs (operation_type, started_at DESC);

-- One generation snapshot per roadmap version (spec section 39.2): the Agent Context
-- actually used, the model draft, the rendered view, and the run that produced it.
-- input_sha256 lets an identical request reuse the saved roadmap without a model call.
CREATE TABLE app.roadmap_generations (
    generation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roadmap_id bigint NOT NULL UNIQUE
        REFERENCES app.roadmaps (roadmap_id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    goal_id bigint NOT NULL
        REFERENCES app.user_career_goals (goal_id) ON DELETE CASCADE,
    ai_run_id bigint REFERENCES system.ai_runs (ai_run_id) ON DELETE SET NULL,
    input_sha256 text NOT NULL CHECK (input_sha256 ~ '^[0-9a-f]{64}$'),
    context_id text NOT NULL,
    prompt_version text NOT NULL,
    model_provider text NOT NULL,
    model_id text NOT NULL,
    agent_context jsonb NOT NULL,
    draft jsonb NOT NULL,
    view jsonb NOT NULL,
    validation_warnings jsonb NOT NULL DEFAULT '[]'::jsonb,
    usage jsonb NOT NULL DEFAULT '{}'::jsonb,
    estimated_cost_usd numeric(10, 6) NOT NULL DEFAULT 0 CHECK (estimated_cost_usd >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_roadmap_generations_goal_input
    ON app.roadmap_generations (goal_id, input_sha256);
