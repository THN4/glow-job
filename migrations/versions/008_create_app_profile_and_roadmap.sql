CREATE SCHEMA IF NOT EXISTS app;

CREATE TYPE app.proficiency_level AS ENUM (
    'beginner', 'intermediate', 'advanced', 'expert', 'unknown'
);
CREATE TYPE app.extraction_status AS ENUM (
    'pending', 'processing', 'completed', 'failed'
);
CREATE TYPE app.review_status AS ENUM (
    'pending', 'confirmed', 'edited', 'rejected'
);
CREATE TYPE app.roadmap_status AS ENUM (
    'draft', 'active', 'completed', 'replaced', 'archived'
);
CREATE TYPE app.progress_status AS ENUM (
    'not_started', 'in_progress', 'completed', 'skipped'
);
CREATE TYPE app.experience_type AS ENUM (
    'work', 'internship', 'project', 'competition', 'course', 'other'
);
CREATE TYPE app.current_situation AS ENUM (
    'student', 'employed_full_time', 'employed_part_time',
    'between_opportunities', 'other'
);
CREATE TYPE app.weekly_availability_band AS ENUM (
    'under_2_hours', 'hours_2_to_5', 'hours_5_to_10', 'hours_10_plus'
);
CREATE TYPE app.learning_preference AS ENUM (
    'structured_courses', 'hands_on_projects', 'reading_articles',
    'videos_tutorials'
);
CREATE TYPE app.readiness_timeframe AS ENUM (
    'three_months', 'six_months', 'one_year', 'no_fixed_deadline'
);
CREATE TYPE app.user_skill_match_status AS ENUM (
    'matched', 'needs_review', 'unmatched'
);
CREATE TYPE app.certification_kind AS ENUM (
    'certification', 'award', 'competition', 'workshop', 'activity',
    'license', 'other'
);
CREATE TYPE app.date_precision AS ENUM ('year', 'month', 'day');
CREATE TYPE app.application_status AS ENUM (
    'interested', 'applied', 'interviewing', 'offered', 'rejected', 'withdrawn'
);
CREATE TYPE app.interview_session_status AS ENUM (
    'in_progress', 'completed', 'abandoned'
);

CREATE TABLE app.users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    auth_provider text NOT NULL,
    auth_subject text,
    password_hash text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_auth_identity UNIQUE (auth_provider, auth_subject)
);

CREATE TABLE app.user_profiles (
    user_id bigint PRIMARY KEY REFERENCES app.users (user_id) ON DELETE CASCADE,
    display_name text,
    current_status app.current_situation,
    current_job_title text,
    years_experience numeric(5, 2) CHECK (years_experience >= 0),
    location text,
    education_level text,
    field_of_study text,
    background_summary text,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app.resumes (
    resume_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    file_name text NOT NULL,
    storage_key text NOT NULL,
    mime_type text,
    file_size_bytes bigint CHECK (file_size_bytes >= 0),
    is_current boolean NOT NULL DEFAULT false,
    uploaded_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_resumes_one_current_per_user
    ON app.resumes (user_id) WHERE is_current;

CREATE TABLE app.resume_extractions (
    extraction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resume_id bigint NOT NULL REFERENCES app.resumes (resume_id) ON DELETE CASCADE,
    status app.extraction_status NOT NULL DEFAULT 'pending',
    model_provider text,
    model_name text,
    extracted_text text,
    extracted_json jsonb,
    review_status app.review_status NOT NULL DEFAULT 'pending',
    started_at timestamptz,
    completed_at timestamptz,
    error_message text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_resume_extractions_resume_id
    ON app.resume_extractions (resume_id);

CREATE TABLE app.user_educations (
    education_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    institution_name text,
    degree text,
    field_of_study text,
    start_date date,
    start_date_precision app.date_precision,
    end_date date,
    end_date_precision app.date_precision,
    description text,
    source text,
    source_resume_id bigint REFERENCES app.resumes (resume_id) ON DELETE SET NULL,
    extraction_confidence numeric(4, 3)
        CHECK (extraction_confidence BETWEEN 0 AND 1),
    user_confirmed boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_user_educations_user_id ON app.user_educations (user_id);

CREATE TABLE app.user_experiences (
    experience_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    experience_type app.experience_type NOT NULL,
    title text NOT NULL,
    organization text,
    role text,
    location text,
    url text,
    description text,
    highlights jsonb CHECK (highlights IS NULL OR jsonb_typeof(highlights) = 'array'),
    start_date date,
    start_date_precision app.date_precision,
    end_date date,
    end_date_precision app.date_precision,
    is_current boolean NOT NULL DEFAULT false,
    source text,
    source_resume_id bigint REFERENCES app.resumes (resume_id) ON DELETE SET NULL,
    extraction_confidence numeric(4, 3)
        CHECK (extraction_confidence BETWEEN 0 AND 1),
    user_confirmed boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_user_experiences_user_id ON app.user_experiences (user_id);

CREATE TABLE app.user_skills (
    user_skill_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    skill_id bigint REFERENCES core.skills (skill_id) ON DELETE RESTRICT,
    raw_skill_name text NOT NULL,
    normalized_skill_name text,
    match_status app.user_skill_match_status NOT NULL DEFAULT 'unmatched',
    proficiency_level app.proficiency_level NOT NULL DEFAULT 'unknown',
    source text,
    confidence numeric(4, 3) CHECK (confidence BETWEEN 0 AND 1),
    verification_type text,
    user_confirmed boolean NOT NULL DEFAULT false,
    first_added_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_skills_catalog_match CHECK (
        (skill_id IS NULL AND match_status IN ('unmatched', 'needs_review'))
        OR (skill_id IS NOT NULL AND match_status = 'matched')
    ),
    CONSTRAINT uq_user_skills_catalog_skill UNIQUE (user_id, skill_id)
);
CREATE INDEX ix_user_skills_raw_name ON app.user_skills (user_id, raw_skill_name);

CREATE TABLE app.user_skill_evidence (
    evidence_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_skill_id bigint NOT NULL
        REFERENCES app.user_skills (user_skill_id) ON DELETE CASCADE,
    resume_id bigint REFERENCES app.resumes (resume_id) ON DELETE SET NULL,
    experience_id bigint
        REFERENCES app.user_experiences (experience_id) ON DELETE SET NULL,
    evidence_type text NOT NULL,
    evidence_text text,
    confidence numeric(4, 3) CHECK (confidence BETWEEN 0 AND 1),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_user_skill_evidence_user_skill_id
    ON app.user_skill_evidence (user_skill_id);

CREATE TABLE app.user_career_goals (
    goal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    target_role_title text NOT NULL,
    career_id bigint REFERENCES core.careers (career_id) ON DELETE RESTRICT,
    career_profile_id bigint
        REFERENCES core.career_profiles (career_profile_id) ON DELETE RESTRICT,
    is_primary boolean NOT NULL DEFAULT false,
    readiness_timeframe app.readiness_timeframe,
    target_date date,
    weekly_availability app.weekly_availability_band,
    available_hours_per_week numeric(5, 2)
        CHECK (available_hours_per_week IS NULL OR available_hours_per_week >= 0),
    preferred_learning_style app.learning_preference,
    additional_context varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_career_goals_catalog_pair CHECK (
        (career_id IS NULL AND career_profile_id IS NULL)
        OR (career_id IS NOT NULL AND career_profile_id IS NOT NULL)
    )
);
CREATE UNIQUE INDEX uq_user_career_goals_one_primary_per_user
    ON app.user_career_goals (user_id) WHERE is_primary;
CREATE INDEX ix_user_career_goals_career_profile_id
    ON app.user_career_goals (career_profile_id);

CREATE TABLE app.user_certifications (
    certification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    kind app.certification_kind NOT NULL DEFAULT 'certification',
    name text NOT NULL,
    issuer text,
    awarded_on date,
    awarded_on_precision app.date_precision,
    details text,
    source text,
    source_resume_id bigint REFERENCES app.resumes (resume_id) ON DELETE SET NULL,
    extraction_confidence numeric(4, 3)
        CHECK (extraction_confidence BETWEEN 0 AND 1),
    user_confirmed boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_user_certifications_user_id
    ON app.user_certifications (user_id);

CREATE TABLE app.roadmaps (
    roadmap_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    goal_id bigint NOT NULL
        REFERENCES app.user_career_goals (goal_id) ON DELETE CASCADE,
    career_id bigint NOT NULL REFERENCES core.careers (career_id) ON DELETE RESTRICT,
    career_profile_id bigint NOT NULL
        REFERENCES core.career_profiles (career_profile_id) ON DELETE RESTRICT,
    version integer NOT NULL CHECK (version > 0),
    title text NOT NULL,
    status app.roadmap_status NOT NULL DEFAULT 'draft',
    generation_reason text NOT NULL,
    previous_roadmap_id bigint
        REFERENCES app.roadmaps (roadmap_id) ON DELETE SET NULL,
    generated_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_roadmaps_goal_version UNIQUE (goal_id, version)
);
CREATE INDEX ix_roadmaps_user_id ON app.roadmaps (user_id);

CREATE TABLE app.roadmap_steps (
    roadmap_step_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roadmap_id bigint NOT NULL
        REFERENCES app.roadmaps (roadmap_id) ON DELETE CASCADE,
    step_number integer NOT NULL CHECK (step_number > 0),
    skill_id bigint REFERENCES core.skills (skill_id) ON DELETE RESTRICT,
    module_id bigint,
    title text NOT NULL,
    description text,
    current_level app.proficiency_level,
    target_level app.proficiency_level,
    reason text,
    estimated_hours numeric(6, 2)
        CHECK (estimated_hours IS NULL OR estimated_hours >= 0),
    is_required boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_roadmap_steps_number UNIQUE (roadmap_id, step_number)
);

CREATE TABLE app.roadmap_tasks (
    task_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roadmap_step_id bigint NOT NULL
        REFERENCES app.roadmap_steps (roadmap_step_id) ON DELETE CASCADE,
    task_number integer NOT NULL CHECK (task_number > 0),
    title text NOT NULL,
    description text,
    is_required boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_roadmap_tasks_number UNIQUE (roadmap_step_id, task_number)
);

CREATE TABLE app.user_roadmap_progress (
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    roadmap_step_id bigint NOT NULL
        REFERENCES app.roadmap_steps (roadmap_step_id) ON DELETE CASCADE,
    status app.progress_status NOT NULL DEFAULT 'not_started',
    progress_percentage numeric(5, 2) NOT NULL DEFAULT 0
        CHECK (progress_percentage BETWEEN 0 AND 100),
    user_note text,
    started_at timestamptz,
    completed_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, roadmap_step_id)
);

CREATE TABLE app.user_task_progress (
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    task_id bigint NOT NULL
        REFERENCES app.roadmap_tasks (task_id) ON DELETE CASCADE,
    status app.progress_status NOT NULL DEFAULT 'not_started',
    completed_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, task_id)
);

CREATE TABLE app.job_applications (
    application_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    job_id bigint REFERENCES market.job_postings (job_id) ON DELETE SET NULL,
    company_id bigint REFERENCES core.companies (company_id) ON DELETE SET NULL,
    job_title text NOT NULL,
    status app.application_status NOT NULL DEFAULT 'interested',
    applied_at timestamptz,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app.application_feedback (
    feedback_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id bigint NOT NULL
        REFERENCES app.job_applications (application_id) ON DELETE CASCADE,
    feedback_type text,
    feedback_text text,
    extracted_reason text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app.interview_sessions (
    interview_session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (user_id) ON DELETE CASCADE,
    job_id bigint REFERENCES market.job_postings (job_id) ON DELETE SET NULL,
    career_id bigint REFERENCES core.careers (career_id) ON DELETE SET NULL,
    status app.interview_session_status NOT NULL DEFAULT 'in_progress',
    started_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz
);

CREATE TABLE app.interview_feedback (
    feedback_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_session_id bigint NOT NULL
        REFERENCES app.interview_sessions (interview_session_id) ON DELETE CASCADE,
    question text NOT NULL,
    user_response text,
    score numeric(5, 2) CHECK (score IS NULL OR score BETWEEN 0 AND 100),
    feedback text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE system.ai_runs (
    ai_run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES app.users (user_id) ON DELETE SET NULL,
    operation_type text NOT NULL,
    model_provider text,
    model_name text,
    status text NOT NULL,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    error_message text
);
CREATE INDEX ix_ai_runs_user_id_started_at
    ON system.ai_runs (user_id, started_at DESC);
